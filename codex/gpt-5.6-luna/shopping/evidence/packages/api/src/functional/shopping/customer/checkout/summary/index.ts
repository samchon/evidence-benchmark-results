import type * as api from "@benchmark/shopping2-api";
import { type IConnection, PlainFetcher } from "@nestia/fetcher";
import typia, { type Primitive, Resolved } from "typia";

/**
 * Start checkout and review the order summary.
 *
 * @evidence docs/analysis/03-functional-requirements.md#req-checkout-journey-2-review-the-order-summary This operation implements the referenced requirement at the generated API boundary.
 * @evidence docs/analysis/03-functional-requirements.md#req-checkout-journey-3-confirm-and-initiate-payment This operation implements the referenced requirement at the generated API boundary.
 *
 * @controller ShoppingCommerceController.checkoutSummary
 * @path GET /shopping/customer/checkout/summary
 * @accessor api.functional.shopping.customer.checkout.summary.checkoutSummary
 * @nestia Generated by Nestia - https://github.com/samchon/nestia
 */
export async function checkoutSummary(
  connection: IConnection<checkoutSummary.Headers>,
): Promise<checkoutSummary.Output> {
  return true === connection.simulate
    ? checkoutSummary.simulate(connection)
    : PlainFetcher.fetch(connection, {
        ...checkoutSummary.METADATA,
        template: checkoutSummary.METADATA.path,
        path: checkoutSummary.path(),
      });
}
export namespace checkoutSummary {
  export type Headers = Resolved<{ authorization?: string }>;
  export type Output = Primitive<api.IShoppingCart>;

  export const METADATA = {
    method: "GET",
    path: "/shopping/customer/checkout/summary",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
    status: 200,
  } as const;

  export const path = () => "/shopping/customer/checkout/summary";
  export const random = (): Resolved<Primitive<api.IShoppingCart>> =>
    typia.random<Primitive<api.IShoppingCart>>();
  export const simulate = (
    _connection: IConnection<checkoutSummary.Headers>,
  ): Output => {
    return random();
  };
}


