export async function customerRecover(
  connection: IConnection,
  body: customerRecover.Body,
): Promise<customerRecover.Output> {
  return true === connection.simulate
    ? customerRecover.simulate(connection, body)
    : PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...customerRecover.METADATA,
          template: customerRecover.METADATA.path,
          path: customerRecover.path(),
        },
        body,
      );
}
export namespace customerRecover {
  export type Body = Primitive<api.IShoppingCustomer.ILogin>;
  export type Output = Primitive<api.IShoppingResult>;

  export const METADATA = {
    method: "POST",
    path: "/shopping/customer/auth/recover",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
    status: 201,
  } as const;

  export const path = () => "/shopping/customer/auth/recover";
  export const random = (): Resolved<Primitive<api.IShoppingResult>> =>
    typia.random<Primitive<api.IShoppingResult>>();
  export const simulate = (connection: IConnection, body: Body): Output => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: path(),
      contentType: "application/json",
    });
    assert.body(() => typia.assert(body));
    return random();
  };
}


