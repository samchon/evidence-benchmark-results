import type * as api from "@benchmark/shopping2-api";
import { type IConnection, NestiaSimulator, PlainFetcher } from "@nestia/fetcher";
import typia, { type Primitive, Resolved } from "typia";

/**
 * Change a seller password.
 *
 * @evidence docs/analysis/01-actors-and-auth.md#req-seller-identity-6-change-the-seller-password This operation implements the referenced requirement at the generated API boundary.
 *
 * @controller ShoppingAuthController.sellerPassword
 * @path PUT /shopping/seller/auth/password
 * @accessor api.functional.shopping.seller.auth.password.sellerPassword
 * @nestia Generated by Nestia - https://github.com/samchon/nestia
 */
export async function sellerPassword(
  connection: IConnection<sellerPassword.Headers>,
  body: sellerPassword.Body,
): Promise<sellerPassword.Output> {
  return true === connection.simulate
    ? sellerPassword.simulate(connection, body)
    : PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...sellerPassword.METADATA,
          template: sellerPassword.METADATA.path,
          path: sellerPassword.path(),
        },
        body,
      );
}
export namespace sellerPassword {
  export type Headers = Resolved<{ authorization?: string }>;
  export type Body = Primitive<api.IShoppingSeller.IPasswordChange>;
  export type Output = Primitive<api.IShoppingResult>;

  export const METADATA = {
    method: "PUT",
    path: "/shopping/seller/auth/password",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
    status: 200,
  } as const;

  export const path = () => "/shopping/seller/auth/password";
  export const random = (): Resolved<Primitive<api.IShoppingResult>> =>
    typia.random<Primitive<api.IShoppingResult>>();
  export const simulate = (
    connection: IConnection<sellerPassword.Headers>,
    body: Body,
  ): Output => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: path(),
      contentType: "application/json",
    });
    assert.body(() => typia.assert(body));
    return random();
  };
}


