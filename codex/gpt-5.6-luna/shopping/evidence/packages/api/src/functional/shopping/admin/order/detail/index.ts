import type * as api from "@benchmark/shopping2-api";
import { type IConnection, NestiaSimulator, PlainFetcher } from "@nestia/fetcher";
import typia, { type Primitive, Resolved, tags } from "typia";

/**
 * View a platform order.
 *
 * @evidence docs/analysis/03-functional-requirements.md#req-order-oversight-2-view-a-platform-order This operation implements the referenced requirement at the generated API boundary.
 *
 * @controller ShoppingAdminGovernanceController.order
 * @path GET /shopping/admin/order/:id/detail
 * @accessor api.functional.shopping.admin.order.detail.order
 * @nestia Generated by Nestia - https://github.com/samchon/nestia
 */
export async function order(
  connection: IConnection<order.Headers>,
  id: string & tags.Format<"uuid">,
): Promise<order.Output> {
  return true === connection.simulate
    ? order.simulate(connection, id)
    : PlainFetcher.fetch(connection, {
        ...order.METADATA,
        template: order.METADATA.path,
        path: order.path(id),
      });
}
export namespace order {
  export type Headers = Resolved<{ authorization?: string }>;
  export type Output = Primitive<api.IShoppingOrder>;

  export const METADATA = {
    method: "GET",
    path: "/shopping/admin/order/:id/detail",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
    status: 200,
  } as const;

  export const path = (id: string & tags.Format<"uuid">) =>
    `/shopping/admin/order/${encodeURIComponent(
      id?.toString() ?? "null",
    )}/detail`;
  export const random = (): Resolved<Primitive<api.IShoppingOrder>> =>
    typia.random<Primitive<api.IShoppingOrder>>();
  export const simulate = (
    connection: IConnection<order.Headers>,
    id: string & tags.Format<"uuid">,
  ): Output => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: path(id),
      contentType: "application/json",
    });
    assert.param("id")(() => typia.assert(id));
    return random();
  };
}


