import type * as api from "@benchmark/shopping2-api";
import { type IConnection, NestiaSimulator, PlainFetcher } from "@nestia/fetcher";
import typia, { type Primitive, Resolved, tags } from "typia";

/**
 * Force-refund one order item.
 *
 * @evidence docs/analysis/03-functional-requirements.md#req-order-oversight-5-force-refund-one-order-item This operation implements the referenced requirement at the generated API boundary.
 *
 * @controller ShoppingAdminGovernanceController.refundItem
 * @path PUT /shopping/admin/order/item/:id/refund
 * @accessor api.functional.shopping.admin.order.item.refund.refundItem
 * @nestia Generated by Nestia - https://github.com/samchon/nestia
 */
export async function refundItem(
  connection: IConnection<refundItem.Headers>,
  id: string & tags.Format<"uuid">,
): Promise<refundItem.Output> {
  return true === connection.simulate
    ? refundItem.simulate(connection, id)
    : PlainFetcher.fetch(connection, {
        ...refundItem.METADATA,
        template: refundItem.METADATA.path,
        path: refundItem.path(id),
      });
}
export namespace refundItem {
  export type Headers = Resolved<{ authorization?: string }>;
  export type Output = Primitive<api.IShoppingResult>;

  export const METADATA = {
    method: "PUT",
    path: "/shopping/admin/order/item/:id/refund",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
    status: 200,
  } as const;

  export const path = (id: string & tags.Format<"uuid">) =>
    `/shopping/admin/order/item/${encodeURIComponent(
      id?.toString() ?? "null",
    )}/refund`;
  export const random = (): Resolved<Primitive<api.IShoppingResult>> =>
    typia.random<Primitive<api.IShoppingResult>>();
  export const simulate = (
    connection: IConnection<refundItem.Headers>,
    id: string & tags.Format<"uuid">,
  ): Output => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: path(id),
      contentType: "application/json",
    });
    assert.param("id")(() => typia.assert(id));
    return random();
  };
}


