import type * as api from "@benchmark/shopping2-api";
import { type IConnection, NestiaSimulator, PlainFetcher } from "@nestia/fetcher";
import typia, { type Primitive, Resolved, tags } from "typia";

/**
 * View a public seller profile.
 *
 * @evidence docs/analysis/03-functional-requirements.md#req-seller-profile-functions-3-view-a-public-seller-profile This operation implements the referenced requirement at the generated API boundary.
 * @evidence prisma:shopping_seller_profiles This operation uses the referenced persistence model for its request or response data.
 *
 * @controller ShoppingCatalogController.seller
 * @path GET /shopping/catalog/seller/:id/profile
 * @accessor api.functional.shopping.catalog.seller.profile.seller
 * @nestia Generated by Nestia - https://github.com/samchon/nestia
 */
export async function seller(
  connection: IConnection,
  id: string & tags.Format<"uuid">,
): Promise<seller.Output> {
  return true === connection.simulate
    ? seller.simulate(connection, id)
    : PlainFetcher.fetch(connection, {
        ...seller.METADATA,
        template: seller.METADATA.path,
        path: seller.path(id),
      });
}
export namespace seller {
  export type Output = Primitive<api.IShoppingSeller.IProfile>;

  export const METADATA = {
    method: "GET",
    path: "/shopping/catalog/seller/:id/profile",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
    status: 200,
  } as const;

  export const path = (id: string & tags.Format<"uuid">) =>
    `/shopping/catalog/seller/${encodeURIComponent(
      id?.toString() ?? "null",
    )}/profile`;
  export const random = (): Resolved<Primitive<api.IShoppingSeller.IProfile>> =>
    typia.random<Primitive<api.IShoppingSeller.IProfile>>();
  export const simulate = (
    connection: IConnection,
    id: string & tags.Format<"uuid">,
  ): Output => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: path(id),
      contentType: "application/json",
    });
    assert.param("id")(() => typia.assert(id));
    return random();
  };
}


