import type * as api from "@benchmark/shopping2-api";
import { type IConnection, NestiaSimulator, PlainFetcher } from "@nestia/fetcher";
import typia, { type Primitive, Resolved, tags } from "typia";

/**
 * Reorder product images.
 *
 * @evidence docs/analysis/03-functional-requirements.md#req-product-image-functions-2-reorder-product-images This operation implements the referenced requirement at the generated API boundary.
 * @evidence prisma:shopping_product_images This operation uses the referenced persistence model for its request or response data.
 *
 * @controller ShoppingCatalogController.imageReorder
 * @path PUT /shopping/catalog/product/:id/image/reorder
 * @accessor api.functional.shopping.catalog.product.image.reorder.imageReorder
 * @nestia Generated by Nestia - https://github.com/samchon/nestia
 */
export async function imageReorder(
  connection: IConnection<imageReorder.Headers>,
  id: string & tags.Format<"uuid">,
  body: imageReorder.Body,
): Promise<imageReorder.Output> {
  return true === connection.simulate
    ? imageReorder.simulate(connection, id, body)
    : PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...imageReorder.METADATA,
          template: imageReorder.METADATA.path,
          path: imageReorder.path(id),
        },
        body,
      );
}
export namespace imageReorder {
  export type Headers = Resolved<{ authorization?: string }>;
  export type Body = Primitive<api.IShoppingProduct.IImageReorder>;
  export type Output = Primitive<Array<api.IShoppingProduct.IImage>>;

  export const METADATA = {
    method: "PUT",
    path: "/shopping/catalog/product/:id/image/reorder",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
    status: 200,
  } as const;

  export const path = (id: string & tags.Format<"uuid">) =>
    `/shopping/catalog/product/${encodeURIComponent(
      id?.toString() ?? "null",
    )}/image/reorder`;
  export const random = (): Resolved<
    Primitive<Array<api.IShoppingProduct.IImage>>
  > => typia.random<Primitive<Array<api.IShoppingProduct.IImage>>>();
  export const simulate = (
    connection: IConnection<imageReorder.Headers>,
    id: string & tags.Format<"uuid">,
    body: Body,
  ): Output => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: path(id),
      contentType: "application/json",
    });
    assert.param("id")(() => typia.assert(id));
    assert.body(() => typia.assert(body));
    return random();
  };
}


