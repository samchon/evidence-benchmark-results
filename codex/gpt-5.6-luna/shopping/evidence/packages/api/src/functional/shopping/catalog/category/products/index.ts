import type * as api from "@benchmark/shopping2-api";
import { type IConnection, NestiaSimulator, PlainFetcher } from "@nestia/fetcher";
import typia, { type Primitive, Resolved, tags } from "typia";

/**
 * View products in a category.
 *
 * @evidence docs/analysis/03-functional-requirements.md#req-category-functions-5-view-products-in-a-category This operation implements the referenced requirement at the generated API boundary.
 * @evidence prisma:shopping_products This operation uses the referenced persistence model for its request or response data.
 *
 * @controller ShoppingCatalogController.categoryProducts
 * @path PATCH /shopping/catalog/category/:id/products
 * @accessor api.functional.shopping.catalog.category.products.categoryProducts
 * @nestia Generated by Nestia - https://github.com/samchon/nestia
 */
export async function categoryProducts(
  connection: IConnection,
  id: string & tags.Format<"uuid">,
  input: categoryProducts.Body,
): Promise<categoryProducts.Output> {
  return true === connection.simulate
    ? categoryProducts.simulate(connection, id, input)
    : PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...categoryProducts.METADATA,
          template: categoryProducts.METADATA.path,
          path: categoryProducts.path(id),
        },
        input,
      );
}
export namespace categoryProducts {
  export type Body = Primitive<api.IShoppingProduct.IRequest>;
  export type Output = Primitive<api.IPage<api.IShoppingProduct.ISummary>>;

  export const METADATA = {
    method: "PATCH",
    path: "/shopping/catalog/category/:id/products",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
    status: 200,
  } as const;

  export const path = (id: string & tags.Format<"uuid">) =>
    `/shopping/catalog/category/${encodeURIComponent(
      id?.toString() ?? "null",
    )}/products`;
  export const random = (): Resolved<
    Primitive<api.IPage<api.IShoppingProduct.ISummary>>
  > => typia.random<Primitive<api.IPage<api.IShoppingProduct.ISummary>>>();
  export const simulate = (
    connection: IConnection,
    id: string & tags.Format<"uuid">,
    input: Body,
  ): Output => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: path(id),
      contentType: "application/json",
    });
    assert.param("id")(() => typia.assert(id));
    assert.body(() => typia.assert(input));
    return random();
  };
}


