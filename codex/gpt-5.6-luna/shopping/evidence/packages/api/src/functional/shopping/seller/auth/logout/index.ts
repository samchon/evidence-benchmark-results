/**
 * Log out the current seller session.
 *
 * @evidence docs/analysis/01-actors-and-auth.md#req-seller-identity-4-log-out-the-current-seller-session This operation implements the referenced requirement at the generated API boundary.
 *
 * @controller ShoppingAuthController.sellerLogout
 * @path POST /shopping/seller/auth/logout
 * @accessor api.functional.shopping.seller.auth.logout.sellerLogout
 * @nestia Generated by Nestia - https://github.com/samchon/nestia
 */
export async function sellerLogout(
  connection: IConnection<sellerLogout.Headers>,
): Promise<sellerLogout.Output> {
  return true === connection.simulate
    ? sellerLogout.simulate(connection)
    : PlainFetcher.fetch(connection, {
        ...sellerLogout.METADATA,
        template: sellerLogout.METADATA.path,
        path: sellerLogout.path(),
      });
}
export namespace sellerLogout {
  export type Headers = Resolved<{ authorization?: string }>;
  export type Output = Primitive<api.IShoppingResult>;

  export const METADATA = {
    method: "POST",
    path: "/shopping/seller/auth/logout",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
    status: 201,
  } as const;

  export const path = () => "/shopping/seller/auth/logout";
  export const random = (): Resolved<Primitive<api.IShoppingResult>> =>
    typia.random<Primitive<api.IShoppingResult>>();
  export const simulate = (
    _connection: IConnection<sellerLogout.Headers>,
  ): Output => {
    return random();
  };
}


