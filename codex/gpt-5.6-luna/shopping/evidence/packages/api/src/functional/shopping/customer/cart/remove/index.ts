import type * as api from "@benchmark/shopping2-api";
import { type IConnection, NestiaSimulator, PlainFetcher } from "@nestia/fetcher";
import typia, { type Primitive, Resolved, tags } from "typia";

/**
 * Remove a cart line.
 *
 * @evidence docs/analysis/03-functional-requirements.md#req-cart-functions-4-remove-a-cart-line This operation implements the referenced requirement at the generated API boundary.
 * @evidence prisma:shopping_cart_lines This operation uses the referenced persistence model for its request or response data.
 *
 * @controller ShoppingCommerceController.cartRemove
 * @path DELETE /shopping/customer/cart/:id/remove
 * @accessor api.functional.shopping.customer.cart.remove.cartRemove
 * @nestia Generated by Nestia - https://github.com/samchon/nestia
 */
export async function cartRemove(
  connection: IConnection<cartRemove.Headers>,
  id: string & tags.Format<"uuid">,
): Promise<cartRemove.Output> {
  return true === connection.simulate
    ? cartRemove.simulate(connection, id)
    : PlainFetcher.fetch(connection, {
        ...cartRemove.METADATA,
        template: cartRemove.METADATA.path,
        path: cartRemove.path(id),
      });
}
export namespace cartRemove {
  export type Headers = Resolved<{ authorization?: string }>;
  export type Output = Primitive<api.IShoppingCart>;

  export const METADATA = {
    method: "DELETE",
    path: "/shopping/customer/cart/:id/remove",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
    status: 200,
  } as const;

  export const path = (id: string & tags.Format<"uuid">) =>
    `/shopping/customer/cart/${encodeURIComponent(
      id?.toString() ?? "null",
    )}/remove`;
  export const random = (): Resolved<Primitive<api.IShoppingCart>> =>
    typia.random<Primitive<api.IShoppingCart>>();
  export const simulate = (
    connection: IConnection<cartRemove.Headers>,
    id: string & tags.Format<"uuid">,
  ): Output => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: path(id),
      contentType: "application/json",
    });
    assert.param("id")(() => typia.assert(id));
    return random();
  };
}


