import type * as api from "@benchmark/shopping2-api";
import { type IConnection, NestiaSimulator, PlainFetcher } from "@nestia/fetcher";
import typia, { type Primitive, Resolved, tags } from "typia";

/**
 * Reject an administrator application.
 *
 * @evidence docs/analysis/03-functional-requirements.md#req-admin-request-functions-5-reject-an-administrator-application This operation implements the referenced requirement at the generated API boundary.
 *
 * @controller ShoppingAdminGovernanceController.requestReject
 * @path PUT /shopping/admin/request/:id/reject
 * @accessor api.functional.shopping.admin.request.reject.requestReject
 * @nestia Generated by Nestia - https://github.com/samchon/nestia
 */
export async function requestReject(
  connection: IConnection<requestReject.Headers>,
  id: string & tags.Format<"uuid">,
  body: requestReject.Body,
): Promise<requestReject.Output> {
  return true === connection.simulate
    ? requestReject.simulate(connection, id, body)
    : PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...requestReject.METADATA,
          template: requestReject.METADATA.path,
          path: requestReject.path(id),
        },
        body,
      );
}
export namespace requestReject {
  export type Headers = Resolved<{ authorization?: string }>;
  export type Body = Primitive<api.IShoppingAdmin.IRequest>;
  export type Output = Primitive<api.IShoppingResult>;

  export const METADATA = {
    method: "PUT",
    path: "/shopping/admin/request/:id/reject",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
    status: 200,
  } as const;

  export const path = (id: string & tags.Format<"uuid">) =>
    `/shopping/admin/request/${encodeURIComponent(
      id?.toString() ?? "null",
    )}/reject`;
  export const random = (): Resolved<Primitive<api.IShoppingResult>> =>
    typia.random<Primitive<api.IShoppingResult>>();
  export const simulate = (
    connection: IConnection<requestReject.Headers>,
    id: string & tags.Format<"uuid">,
    body: Body,
  ): Output => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: path(id),
      contentType: "application/json",
    });
    assert.param("id")(() => typia.assert(id));
    assert.body(() => typia.assert(body));
    return random();
  };
}


