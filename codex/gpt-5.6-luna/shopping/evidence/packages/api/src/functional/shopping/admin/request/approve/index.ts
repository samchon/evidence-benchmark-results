import type * as api from "@benchmark/shopping2-api";
import { type IConnection, NestiaSimulator, PlainFetcher } from "@nestia/fetcher";
import typia, { type Primitive, Resolved, tags } from "typia";

/**
 * Approve an administrator application.
 *
 * @evidence docs/analysis/03-functional-requirements.md#req-admin-request-functions-4-approve-an-administrator-application This operation implements the referenced requirement at the generated API boundary.
 * @evidence docs/analysis/02-domain-model.md#req-admin-request-domain-2-approve-an-administrator-request Enforces the request domain 2 approve an administrator request contract through requestApprove.
 *
 * @controller ShoppingAdminGovernanceController.requestApprove
 * @path PUT /shopping/admin/request/:id/approve
 * @accessor api.functional.shopping.admin.request.approve.requestApprove
 * @nestia Generated by Nestia - https://github.com/samchon/nestia
 */
export async function requestApprove(
  connection: IConnection<requestApprove.Headers>,
  id: string & tags.Format<"uuid">,
): Promise<requestApprove.Output> {
  return true === connection.simulate
    ? requestApprove.simulate(connection, id)
    : PlainFetcher.fetch(connection, {
        ...requestApprove.METADATA,
        template: requestApprove.METADATA.path,
        path: requestApprove.path(id),
      });
}
export namespace requestApprove {
  export type Headers = Resolved<{ authorization?: string }>;
  export type Output = Primitive<api.IShoppingResult>;

  export const METADATA = {
    method: "PUT",
    path: "/shopping/admin/request/:id/approve",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
    status: 200,
  } as const;

  export const path = (id: string & tags.Format<"uuid">) =>
    `/shopping/admin/request/${encodeURIComponent(
      id?.toString() ?? "null",
    )}/approve`;
  export const random = (): Resolved<Primitive<api.IShoppingResult>> =>
    typia.random<Primitive<api.IShoppingResult>>();
  export const simulate = (
    connection: IConnection<requestApprove.Headers>,
    id: string & tags.Format<"uuid">,
  ): Output => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: path(id),
      contentType: "application/json",
    });
    assert.param("id")(() => typia.assert(id));
    return random();
  };
}


