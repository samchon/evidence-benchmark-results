import type * as api from "@benchmark/shopping2-api";
import { type IConnection, NestiaSimulator, PlainFetcher } from "@nestia/fetcher";
import typia, { type Primitive, Resolved } from "typia";

/**
 * List items awaiting shipment.
 *
 * @evidence docs/analysis/03-functional-requirements.md#req-shipping-functions-1-list-items-awaiting-shipment This operation implements the referenced requirement at the generated API boundary.
 * @evidence prisma:shopping_order_items This operation uses the referenced persistence model for its request or response data.
 *
 * @controller ShoppingFulfillmentController.awaiting
 * @path PATCH /shopping/seller/awaiting-shipment
 * @accessor api.functional.shopping.seller.awaiting_shipment.awaiting
 * @nestia Generated by Nestia - https://github.com/samchon/nestia
 */
export async function awaiting(
  connection: IConnection<awaiting.Headers>,
  input: awaiting.Body,
): Promise<awaiting.Output> {
  return true === connection.simulate
    ? awaiting.simulate(connection, input)
    : PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...awaiting.METADATA,
          template: awaiting.METADATA.path,
          path: awaiting.path(),
        },
        input,
      );
}
export namespace awaiting {
  export type Headers = Resolved<{ authorization?: string }>;
  export type Body = Primitive<api.IPage.IRequest>;
  export type Output = Primitive<api.IPage<api.IShoppingOrder.IItem>>;

  export const METADATA = {
    method: "PATCH",
    path: "/shopping/seller/awaiting-shipment",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
    status: 200,
  } as const;

  export const path = () => "/shopping/seller/awaiting-shipment";
  export const random = (): Resolved<
    Primitive<api.IPage<api.IShoppingOrder.IItem>>
  > => typia.random<Primitive<api.IPage<api.IShoppingOrder.IItem>>>();
  export const simulate = (
    connection: IConnection<awaiting.Headers>,
    input: Body,
  ): Output => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: path(),
      contentType: "application/json",
    });
    assert.body(() => typia.assert(input));
    return random();
  };
}


