import type * as api from "@benchmark/shopping2-api";
import { type IConnection, NestiaSimulator, PlainFetcher } from "@nestia/fetcher";
import typia, { type Primitive, Resolved, tags } from "typia";

export * as auto_confirm from "./auto_confirm/index";

/**
 * View shipment tracking.
 *
 * @evidence docs/analysis/03-functional-requirements.md#req-shipping-functions-3-view-shipment-tracking This generated accessor implements the referenced requirement and delegates the request to the live backend endpoint.
 * @evidence prisma:shopping_shipments This operation uses the referenced persistence model for its request or response data.
 *
 * @controller ShoppingFulfillmentController.tracking
 * @path GET /shopping/shipping/:id/tracking
 * @accessor api.functional.shopping.shipping.tracking
 * @nestia Generated by Nestia - https://github.com/samchon/nestia
 */
export async function tracking(
  connection: IConnection<tracking.Headers>,
  id: string & tags.Format<"uuid">,
): Promise<tracking.Output> {
  return true === connection.simulate
    ? tracking.simulate(connection, id)
    : PlainFetcher.fetch(connection, {
        ...tracking.METADATA,
        template: tracking.METADATA.path,
        path: tracking.path(id),
      });
}
export namespace tracking {
  export type Headers = Resolved<{ authorization?: string }>;
  export type Output = Primitive<api.IShoppingOrder.IShipment>;

  export const METADATA = {
    method: "GET",
    path: "/shopping/shipping/:id/tracking",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
    status: 200,
  } as const;

  export const path = (id: string & tags.Format<"uuid">) =>
    `/shopping/shipping/${encodeURIComponent(
      id?.toString() ?? "null",
    )}/tracking`;
  export const random = (): Resolved<Primitive<api.IShoppingOrder.IShipment>> =>
    typia.random<Primitive<api.IShoppingOrder.IShipment>>();
  export const simulate = (
    connection: IConnection<tracking.Headers>,
    id: string & tags.Format<"uuid">,
  ): Output => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: path(id),
      contentType: "application/json",
    });
    assert.param("id")(() => typia.assert(id));
    return random();
  };
}

