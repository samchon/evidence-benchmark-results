import { type IConnection, NestiaSimulator, PlainFetcher } from "@nestia/fetcher";
import typia, { type Primitive, Resolved, tags } from "typia";

/**
 * View product details.
 *
 * @evidence docs/analysis/03-functional-requirements.md#req-product-discovery-3-view-product-details This operation implements the referenced requirement at the generated API boundary.
 * @evidence prisma:shopping_products This operation uses the referenced persistence model for its request or response data.
 * @evidence docs/analysis/05-non-functional.md#req-nfr-audit-integrity-2-reconstruct-each-recorded-modification Enforces the audit integrity 2 reconstruct each recorded modification contract through product.
 * @evidence docs/analysis/05-non-functional.md#req-nfr-audit-integrity-4-trace-stock-and-purchase-evidence-end-to-end Enforces the audit integrity 4 trace stock and purchase evidence end to end contract through product.
 *
 * @controller ShoppingCatalogController.product
 * @path GET /shopping/catalog/product/:id/detail
 * @accessor api.functional.shopping.catalog.product.detail.product
 * @nestia Generated by Nestia - https://github.com/samchon/nestia
 */
export async function product(
  connection: IConnection,
  id: string & tags.Format<"uuid">,
): Promise<product.Output> {
  return true === connection.simulate
    ? product.simulate(connection, id)
    : PlainFetcher.fetch(connection, {
        ...product.METADATA,
        template: product.METADATA.path,
        path: product.path(id),
      });
}
export namespace product {
  export type Output = Primitive<api.IShoppingProduct>;

  export const METADATA = {
    method: "GET",
    path: "/shopping/catalog/product/:id/detail",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
    status: 200,
  } as const;

  export const path = (id: string & tags.Format<"uuid">) =>
    `/shopping/catalog/product/${encodeURIComponent(
      id?.toString() ?? "null",
    )}/detail`;
  export const random = (): Resolved<Primitive<api.IShoppingProduct>> =>
    typia.random<Primitive<api.IShoppingProduct>>();
  export const simulate = (
    connection: IConnection,
    id: string & tags.Format<"uuid">,
  ): Output => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: path(id),
      contentType: "application/json",
    });
    assert.param("id")(() => typia.assert(id));
    return random();
  };
}


