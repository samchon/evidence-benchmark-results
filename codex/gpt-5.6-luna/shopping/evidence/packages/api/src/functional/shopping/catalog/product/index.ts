export async function snapshots(
  connection: IConnection<snapshots.Headers>,
  id: string & tags.Format<"uuid">,
): Promise<snapshots.Output> {
  return true === connection.simulate
    ? snapshots.simulate(connection, id)
    : PlainFetcher.fetch(connection, {
        ...snapshots.METADATA,
        template: snapshots.METADATA.path,
        path: snapshots.path(id),
      });
}
export namespace snapshots {
  export type Headers = Resolved<{ authorization?: string }>;
  export type Output = Primitive<Array<api.IShoppingProduct.ISnapshot>>;

  export const METADATA = {
    method: "GET",
    path: "/shopping/catalog/product/:id/snapshots",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
    status: 200,
  } as const;

  export const path = (id: string & tags.Format<"uuid">) =>
    `/shopping/catalog/product/${encodeURIComponent(
      id?.toString() ?? "null",
    )}/snapshots`;
  export const random = (): Resolved<
    Primitive<Array<api.IShoppingProduct.ISnapshot>>
  > => typia.random<Primitive<Array<api.IShoppingProduct.ISnapshot>>>();
  export const simulate = (
    connection: IConnection<snapshots.Headers>,
    id: string & tags.Format<"uuid">,
  ): Output => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: path(id),
      contentType: "application/json",
    });
    assert.param("id")(() => typia.assert(id));
    return random();
  };
}


