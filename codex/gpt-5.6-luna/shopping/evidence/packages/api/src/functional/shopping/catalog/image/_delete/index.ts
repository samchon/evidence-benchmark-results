export async function imageDelete(
  connection: IConnection<imageDelete.Headers>,
  id: string & tags.Format<"uuid">,
): Promise<imageDelete.Output> {
  return true === connection.simulate
    ? imageDelete.simulate(connection, id)
    : PlainFetcher.fetch(connection, {
        ...imageDelete.METADATA,
        template: imageDelete.METADATA.path,
        path: imageDelete.path(id),
      });
}
export namespace imageDelete {
  export type Headers = Resolved<{ authorization?: string }>;
  export type Output = Primitive<api.IShoppingResult>;

  export const METADATA = {
    method: "DELETE",
    path: "/shopping/catalog/image/:id/delete",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
    status: 200,
  } as const;

  export const path = (id: string & tags.Format<"uuid">) =>
    `/shopping/catalog/image/${encodeURIComponent(
      id?.toString() ?? "null",
    )}/delete`;
  export const random = (): Resolved<Primitive<api.IShoppingResult>> =>
    typia.random<Primitive<api.IShoppingResult>>();
  export const simulate = (
    connection: IConnection<imageDelete.Headers>,
    id: string & tags.Format<"uuid">,
  ): Output => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: path(id),
      contentType: "application/json",
    });
    assert.param("id")(() => typia.assert(id));
    return random();
  };
}


