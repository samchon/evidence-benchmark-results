import type * as api from "@benchmark/shopping2-api";
import { type IConnection, NestiaSimulator, PlainFetcher } from "@nestia/fetcher";
import typia, { type Primitive, Resolved, tags } from "typia";

/**
 * Upload a product image.
 *
 * @evidence docs/analysis/03-functional-requirements.md#req-product-image-functions-1-upload-product-images This operation implements the referenced requirement at the generated API boundary.
 * @evidence prisma:shopping_product_images This operation uses the referenced persistence model for its request or response data.
 *
 * @controller ShoppingCatalogController.imageCreate
 * @path POST /shopping/catalog/product/:id/image/create
 * @accessor api.functional.shopping.catalog.product.image.create.imageCreate
 * @nestia Generated by Nestia - https://github.com/samchon/nestia
 */
export async function imageCreate(
  connection: IConnection<imageCreate.Headers>,
  id: string & tags.Format<"uuid">,
  body: imageCreate.Body,
): Promise<imageCreate.Output> {
  return true === connection.simulate
    ? imageCreate.simulate(connection, id, body)
    : PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...imageCreate.METADATA,
          template: imageCreate.METADATA.path,
          path: imageCreate.path(id),
        },
        body,
      );
}
export namespace imageCreate {
  export type Headers = Resolved<{ authorization?: string }>;
  export type Body = Primitive<api.IShoppingProduct.IImageCreate>;
  export type Output = Primitive<api.IShoppingProduct.IImage>;

  export const METADATA = {
    method: "POST",
    path: "/shopping/catalog/product/:id/image/create",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
    status: 201,
  } as const;

  export const path = (id: string & tags.Format<"uuid">) =>
    `/shopping/catalog/product/${encodeURIComponent(
      id?.toString() ?? "null",
    )}/image/create`;
  export const random = (): Resolved<Primitive<api.IShoppingProduct.IImage>> =>
    typia.random<Primitive<api.IShoppingProduct.IImage>>();
  export const simulate = (
    connection: IConnection<imageCreate.Headers>,
    id: string & tags.Format<"uuid">,
    body: Body,
  ): Output => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: path(id),
      contentType: "application/json",
    });
    assert.param("id")(() => typia.assert(id));
    assert.body(() => typia.assert(body));
    return random();
  };
}


