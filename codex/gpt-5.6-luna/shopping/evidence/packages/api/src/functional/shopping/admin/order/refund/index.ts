import type * as api from "@benchmark/shopping2-api";
import { type IConnection, NestiaSimulator, PlainFetcher } from "@nestia/fetcher";
import typia, { type Primitive, Resolved, tags } from "typia";

/**
 * Force-refund eligible items in an order.
 *
 * @evidence docs/analysis/03-functional-requirements.md#req-order-oversight-6-force-refund-an-orders-eligible-items This operation implements the referenced requirement at the generated API boundary.
 *
 * @controller ShoppingAdminGovernanceController.refundOrder
 * @path PUT /shopping/admin/order/:id/refund
 * @accessor api.functional.shopping.admin.order.refund.refundOrder
 * @nestia Generated by Nestia - https://github.com/samchon/nestia
 */
export async function refundOrder(
  connection: IConnection<refundOrder.Headers>,
  id: string & tags.Format<"uuid">,
): Promise<refundOrder.Output> {
  return true === connection.simulate
    ? refundOrder.simulate(connection, id)
    : PlainFetcher.fetch(connection, {
        ...refundOrder.METADATA,
        template: refundOrder.METADATA.path,
        path: refundOrder.path(id),
      });
}
export namespace refundOrder {
  export type Headers = Resolved<{ authorization?: string }>;
  export type Output = Primitive<api.IShoppingResult>;

  export const METADATA = {
    method: "PUT",
    path: "/shopping/admin/order/:id/refund",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
    status: 200,
  } as const;

  export const path = (id: string & tags.Format<"uuid">) =>
    `/shopping/admin/order/${encodeURIComponent(
      id?.toString() ?? "null",
    )}/refund`;
  export const random = (): Resolved<Primitive<api.IShoppingResult>> =>
    typia.random<Primitive<api.IShoppingResult>>();
  export const simulate = (
    connection: IConnection<refundOrder.Headers>,
    id: string & tags.Format<"uuid">,
  ): Output => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: path(id),
      contentType: "application/json",
    });
    assert.param("id")(() => typia.assert(id));
    return random();
  };
}


