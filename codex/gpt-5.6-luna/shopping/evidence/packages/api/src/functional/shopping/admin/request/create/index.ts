export async function requestCreate(
  connection: IConnection<requestCreate.Headers>,
  body: requestCreate.Body,
): Promise<requestCreate.Output> {
  return true === connection.simulate
    ? requestCreate.simulate(connection, body)
    : PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...requestCreate.METADATA,
          template: requestCreate.METADATA.path,
          path: requestCreate.path(),
        },
        body,
      );
}
