export async function requestPending(
  connection: IConnection<requestPending.Headers>,
  input: requestPending.Body,
): Promise<requestPending.Output> {
  return true === connection.simulate
    ? requestPending.simulate(connection, input)
    : PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...requestPending.METADATA,
          template: requestPending.METADATA.path,
          path: requestPending.path(),
        },
        input,
      );
}
