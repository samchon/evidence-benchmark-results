import type * as api from "@benchmark/shopping2-api";
import { type IConnection, NestiaSimulator, PlainFetcher } from "@nestia/fetcher";
import typia, { type Primitive, Resolved, tags } from "typia";

/**
 * Remove a wishlist product.
 *
 * @evidence docs/analysis/03-functional-requirements.md#req-wishlist-functions-3-remove-a-wishlist-product This operation implements the referenced requirement at the generated API boundary.
 * @evidence prisma:shopping_wishlist_entries This operation uses the referenced persistence model for its request or response data.
 *
 * @controller ShoppingCommerceController.wishlistRemove
 * @path DELETE /shopping/customer/wishlist/:productId/remove
 * @accessor api.functional.shopping.customer.wishlist.remove.wishlistRemove
 * @nestia Generated by Nestia - https://github.com/samchon/nestia
 */
export async function wishlistRemove(
  connection: IConnection<wishlistRemove.Headers>,
  productId: string & tags.Format<"uuid">,
): Promise<wishlistRemove.Output> {
  return true === connection.simulate
    ? wishlistRemove.simulate(connection, productId)
    : PlainFetcher.fetch(connection, {
        ...wishlistRemove.METADATA,
        template: wishlistRemove.METADATA.path,
        path: wishlistRemove.path(productId),
      });
}
export namespace wishlistRemove {
  export type Headers = Resolved<{ authorization?: string }>;
  export type Output = Primitive<api.IShoppingResult>;

  export const METADATA = {
    method: "DELETE",
    path: "/shopping/customer/wishlist/:productId/remove",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
    status: 200,
  } as const;

  export const path = (productId: string & tags.Format<"uuid">) =>
    `/shopping/customer/wishlist/${encodeURIComponent(
      productId?.toString() ?? "null",
    )}/remove`;
  export const random = (): Resolved<Primitive<api.IShoppingResult>> =>
    typia.random<Primitive<api.IShoppingResult>>();
  export const simulate = (
    connection: IConnection<wishlistRemove.Headers>,
    productId: string & tags.Format<"uuid">,
  ): Output => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: path(productId),
      contentType: "application/json",
    });
    assert.param("productId")(() => typia.assert(productId));
    return random();
  };
}


