export async function orders(
  connection: IConnection<orders.Headers>,
  input: orders.Body,
): Promise<orders.Output> {
  return true === connection.simulate
    ? orders.simulate(connection, input)
    : PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...orders.METADATA,
          template: orders.METADATA.path,
          path: orders.path(),
        },
        input,
      );
}
