import type * as api from "@benchmark/shopping2-api";
import { type IConnection, NestiaSimulator, PlainFetcher } from "@nestia/fetcher";
import typia, { type Primitive, Resolved, tags } from "typia";

/**
 * Demote another super administrator.
 *
 * @evidence docs/analysis/03-functional-requirements.md#req-admin-grade-functions-2-demote-another-super-administrator This operation implements the referenced requirement at the generated API boundary.
 * @evidence docs/analysis/01-actors-and-auth.md#req-admin-authority-5-demote-another-super-administrator Enforces the authority 5 demote another super administrator contract through demote.
 *
 * @controller ShoppingAdminGovernanceController.demote
 * @path PUT /shopping/admin/grade-demote/:id
 * @accessor api.functional.shopping.admin.grade_demote.demote
 * @nestia Generated by Nestia - https://github.com/samchon/nestia
 */
export async function demote(
  connection: IConnection<demote.Headers>,
  id: string & tags.Format<"uuid">,
): Promise<demote.Output> {
  return true === connection.simulate
    ? demote.simulate(connection, id)
    : PlainFetcher.fetch(connection, {
        ...demote.METADATA,
        template: demote.METADATA.path,
        path: demote.path(id),
      });
}
export namespace demote {
  export type Headers = Resolved<{ authorization?: string }>;
  export type Output = Primitive<api.IShoppingResult>;

  export const METADATA = {
    method: "PUT",
    path: "/shopping/admin/grade-demote/:id",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
    status: 200,
  } as const;

  export const path = (id: string & tags.Format<"uuid">) =>
    `/shopping/admin/grade-demote/${encodeURIComponent(
      id?.toString() ?? "null",
    )}`;
  export const random = (): Resolved<Primitive<api.IShoppingResult>> =>
    typia.random<Primitive<api.IShoppingResult>>();
  export const simulate = (
    connection: IConnection<demote.Headers>,
    id: string & tags.Format<"uuid">,
  ): Output => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: path(id),
      contentType: "application/json",
    });
    assert.param("id")(() => typia.assert(id));
    return random();
  };
}


