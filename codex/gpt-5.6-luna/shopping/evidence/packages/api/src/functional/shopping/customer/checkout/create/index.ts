export async function checkout(
  connection: IConnection<checkout.Headers>,
  body: checkout.Body,
): Promise<checkout.Output> {
  return true === connection.simulate
    ? checkout.simulate(connection, body)
    : PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...checkout.METADATA,
          template: checkout.METADATA.path,
          path: checkout.path(),
        },
        body,
      );
}
export namespace checkout {
  export type Headers = Resolved<{ authorization?: string }>;
  export type Body = Primitive<api.IShoppingOrder.ICreate>;
  export type Output = Primitive<api.IShoppingOrder>;

  export const METADATA = {
    method: "POST",
    path: "/shopping/customer/checkout/create",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
    status: 201,
  } as const;

  export const path = () => "/shopping/customer/checkout/create";
  export const random = (): Resolved<Primitive<api.IShoppingOrder>> =>
    typia.random<Primitive<api.IShoppingOrder>>();
  export const simulate = (
    connection: IConnection<checkout.Headers>,
    body: Body,
  ): Output => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: path(),
      contentType: "application/json",
    });
    assert.body(() => typia.assert(body));
    return random();
  };
}


