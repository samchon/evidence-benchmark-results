/**
 * View order shipments.
 *
 * @evidence docs/analysis/03-functional-requirements.md#req-order-history-functions-3-view-order-shipments This operation implements the referenced requirement at the generated API boundary.
 * @evidence prisma:shopping_shipments This operation uses the referenced persistence model for its request or response data.
 *
 * @controller ShoppingCommerceController.shipments
 * @path GET /shopping/customer/order/:id/shipments
 * @accessor api.functional.shopping.customer.order.shipments
 * @nestia Generated by Nestia - https://github.com/samchon/nestia
 */
export async function shipments(
  connection: IConnection<shipments.Headers>,
  id: string & tags.Format<"uuid">,
): Promise<shipments.Output> {
  return true === connection.simulate
    ? shipments.simulate(connection, id)
    : PlainFetcher.fetch(connection, {
        ...shipments.METADATA,
        template: shipments.METADATA.path,
        path: shipments.path(id),
      });
}
export namespace shipments {
  export type Headers = Resolved<{ authorization?: string }>;
  export type Output = Primitive<Array<api.IShoppingOrder.IShipment>>;

  export const METADATA = {
    method: "GET",
    path: "/shopping/customer/order/:id/shipments",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
    status: 200,
  } as const;

  export const path = (id: string & tags.Format<"uuid">) =>
    `/shopping/customer/order/${encodeURIComponent(
      id?.toString() ?? "null",
    )}/shipments`;
  export const random = (): Resolved<
    Primitive<Array<api.IShoppingOrder.IShipment>>
  > => typia.random<Primitive<Array<api.IShoppingOrder.IShipment>>>();
  export const simulate = (
    connection: IConnection<shipments.Headers>,
    id: string & tags.Format<"uuid">,
  ): Output => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: path(id),
      contentType: "application/json",
    });
    assert.param("id")(() => typia.assert(id));
    return random();
  };
}


