import type * as api from "@benchmark/shopping2-api";
import { type IConnection, NestiaSimulator, PlainFetcher } from "@nestia/fetcher";
import typia, { type Primitive, Resolved, tags } from "typia";

/**
 * Unban a seller.
 *
 * @evidence docs/analysis/03-functional-requirements.md#req-user-oversight-6-unban-a-seller This operation implements the referenced requirement at the generated API boundary.
 *
 * @controller ShoppingAdminGovernanceController.unbanSeller
 * @path PUT /shopping/admin/user/seller/:id/unban
 * @accessor api.functional.shopping.admin.user.seller.unban.unbanSeller
 * @nestia Generated by Nestia - https://github.com/samchon/nestia
 */
export async function unbanSeller(
  connection: IConnection<unbanSeller.Headers>,
  id: string & tags.Format<"uuid">,
): Promise<unbanSeller.Output> {
  return true === connection.simulate
    ? unbanSeller.simulate(connection, id)
    : PlainFetcher.fetch(connection, {
        ...unbanSeller.METADATA,
        template: unbanSeller.METADATA.path,
        path: unbanSeller.path(id),
      });
}
export namespace unbanSeller {
  export type Headers = Resolved<{ authorization?: string }>;
  export type Output = Primitive<api.IShoppingResult>;

  export const METADATA = {
    method: "PUT",
    path: "/shopping/admin/user/seller/:id/unban",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
    status: 200,
  } as const;

  export const path = (id: string & tags.Format<"uuid">) =>
    `/shopping/admin/user/seller/${encodeURIComponent(
      id?.toString() ?? "null",
    )}/unban`;
  export const random = (): Resolved<Primitive<api.IShoppingResult>> =>
    typia.random<Primitive<api.IShoppingResult>>();
  export const simulate = (
    connection: IConnection<unbanSeller.Headers>,
    id: string & tags.Format<"uuid">,
  ): Output => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: path(id),
      contentType: "application/json",
    });
    assert.param("id")(() => typia.assert(id));
    return random();
  };
}


