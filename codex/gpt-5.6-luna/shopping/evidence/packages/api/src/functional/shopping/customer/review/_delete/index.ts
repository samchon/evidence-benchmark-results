export async function reviewDelete(
  connection: IConnection<reviewDelete.Headers>,
  id: string & tags.Format<"uuid">,
): Promise<reviewDelete.Output> {
  return true === connection.simulate
    ? reviewDelete.simulate(connection, id)
    : PlainFetcher.fetch(connection, {
        ...reviewDelete.METADATA,
        template: reviewDelete.METADATA.path,
        path: reviewDelete.path(id),
      });
}
export namespace reviewDelete {
  export type Headers = Resolved<{ authorization?: string }>;
  export type Output = Primitive<api.IShoppingResult>;

  export const METADATA = {
    method: "DELETE",
    path: "/shopping/customer/review/:id/delete",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
    status: 200,
  } as const;

  export const path = (id: string & tags.Format<"uuid">) =>
    `/shopping/customer/review/${encodeURIComponent(
      id?.toString() ?? "null",
    )}/delete`;
  export const random = (): Resolved<Primitive<api.IShoppingResult>> =>
    typia.random<Primitive<api.IShoppingResult>>();
  export const simulate = (
    connection: IConnection<reviewDelete.Headers>,
    id: string & tags.Format<"uuid">,
  ): Output => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: path(id),
      contentType: "application/json",
    });
    assert.param("id")(() => typia.assert(id));
    return random();
  };
}


