import type * as api from "@benchmark/shopping2-api";
import { type IConnection, NestiaSimulator, PlainFetcher } from "@nestia/fetcher";
import typia, { type Primitive, Resolved, tags } from "typia";

/**
 * Edit an authored review.
 *
 * @evidence docs/analysis/03-functional-requirements.md#req-review-functions-2-edit-an-authored-review This operation implements the referenced requirement at the generated API boundary.
 * @evidence prisma:shopping_reviews This operation uses the referenced persistence model for its request or response data.
 *
 * @controller ShoppingCommerceController.reviewUpdate
 * @path PUT /shopping/customer/review/:id/update
 * @accessor api.functional.shopping.customer.review.update.reviewUpdate
 * @nestia Generated by Nestia - https://github.com/samchon/nestia
 */
export async function reviewUpdate(
  connection: IConnection<reviewUpdate.Headers>,
  id: string & tags.Format<"uuid">,
  body: reviewUpdate.Body,
): Promise<reviewUpdate.Output> {
  return true === connection.simulate
    ? reviewUpdate.simulate(connection, id, body)
    : PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...reviewUpdate.METADATA,
          template: reviewUpdate.METADATA.path,
          path: reviewUpdate.path(id),
        },
        body,
      );
}
export namespace reviewUpdate {
  export type Headers = Resolved<{ authorization?: string }>;
  export type Body = Primitive<api.IShoppingReview.IUpdate>;
  export type Output = Primitive<api.IShoppingReview>;

  export const METADATA = {
    method: "PUT",
    path: "/shopping/customer/review/:id/update",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
    status: 200,
  } as const;

  export const path = (id: string & tags.Format<"uuid">) =>
    `/shopping/customer/review/${encodeURIComponent(
      id?.toString() ?? "null",
    )}/update`;
  export const random = (): Resolved<Primitive<api.IShoppingReview>> =>
    typia.random<Primitive<api.IShoppingReview>>();
  export const simulate = (
    connection: IConnection<reviewUpdate.Headers>,
    id: string & tags.Format<"uuid">,
    body: Body,
  ): Output => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: path(id),
      contentType: "application/json",
    });
    assert.param("id")(() => typia.assert(id));
    assert.body(() => typia.assert(body));
    return random();
  };
}


