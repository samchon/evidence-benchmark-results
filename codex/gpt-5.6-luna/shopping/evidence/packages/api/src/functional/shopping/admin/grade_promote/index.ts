import type * as api from "@benchmark/shopping2-api";
import { type IConnection, NestiaSimulator, PlainFetcher } from "@nestia/fetcher";
import typia, { type Primitive, Resolved, tags } from "typia";

/**
 * Promote a regular administrator.
 *
 * @evidence docs/analysis/03-functional-requirements.md#req-admin-grade-functions-1-promote-a-regular-administrator This operation implements the referenced requirement at the generated API boundary.
 * @evidence prisma:shopping_administrators This operation uses the referenced persistence model for its request or response data.
 * @evidence docs/analysis/01-actors-and-auth.md#req-admin-authority-4-promote-an-administrator Enforces the authority 4 promote an administrator contract through promote.
 *
 * @controller ShoppingAdminGovernanceController.promote
 * @path PUT /shopping/admin/grade-promote/:id
 * @accessor api.functional.shopping.admin.grade_promote.promote
 * @nestia Generated by Nestia - https://github.com/samchon/nestia
 */
export async function promote(
  connection: IConnection<promote.Headers>,
  id: string & tags.Format<"uuid">,
): Promise<promote.Output> {
  return true === connection.simulate
    ? promote.simulate(connection, id)
    : PlainFetcher.fetch(connection, {
        ...promote.METADATA,
        template: promote.METADATA.path,
        path: promote.path(id),
      });
}
export namespace promote {
  export type Headers = Resolved<{ authorization?: string }>;
  export type Output = Primitive<api.IShoppingResult>;

  export const METADATA = {
    method: "PUT",
    path: "/shopping/admin/grade-promote/:id",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
    status: 200,
  } as const;

  export const path = (id: string & tags.Format<"uuid">) =>
    `/shopping/admin/grade-promote/${encodeURIComponent(
      id?.toString() ?? "null",
    )}`;
  export const random = (): Resolved<Primitive<api.IShoppingResult>> =>
    typia.random<Primitive<api.IShoppingResult>>();
  export const simulate = (
    connection: IConnection<promote.Headers>,
    id: string & tags.Format<"uuid">,
  ): Output => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: path(id),
      contentType: "application/json",
    });
    assert.param("id")(() => typia.assert(id));
    return random();
  };
}


