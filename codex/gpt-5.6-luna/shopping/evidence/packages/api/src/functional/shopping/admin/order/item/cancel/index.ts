import type * as api from "@benchmark/shopping2-api";
import { type IConnection, NestiaSimulator, PlainFetcher } from "@nestia/fetcher";
import typia, { type Primitive, Resolved, tags } from "typia";

/**
 * Force-cancel one order item.
 *
 * @evidence docs/analysis/03-functional-requirements.md#req-order-oversight-3-force-cancel-one-order-item This operation implements the referenced requirement at the generated API boundary.
 *
 * @controller ShoppingAdminGovernanceController.cancelItem
 * @path PUT /shopping/admin/order/item/:id/cancel
 * @accessor api.functional.shopping.admin.order.item.cancel.cancelItem
 * @nestia Generated by Nestia - https://github.com/samchon/nestia
 */
export async function cancelItem(
  connection: IConnection<cancelItem.Headers>,
  id: string & tags.Format<"uuid">,
): Promise<cancelItem.Output> {
  return true === connection.simulate
    ? cancelItem.simulate(connection, id)
    : PlainFetcher.fetch(connection, {
        ...cancelItem.METADATA,
        template: cancelItem.METADATA.path,
        path: cancelItem.path(id),
      });
}
export namespace cancelItem {
  export type Headers = Resolved<{ authorization?: string }>;
  export type Output = Primitive<api.IShoppingResult>;

  export const METADATA = {
    method: "PUT",
    path: "/shopping/admin/order/item/:id/cancel",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
    status: 200,
  } as const;

  export const path = (id: string & tags.Format<"uuid">) =>
    `/shopping/admin/order/item/${encodeURIComponent(
      id?.toString() ?? "null",
    )}/cancel`;
  export const random = (): Resolved<Primitive<api.IShoppingResult>> =>
    typia.random<Primitive<api.IShoppingResult>>();
  export const simulate = (
    connection: IConnection<cancelItem.Headers>,
    id: string & tags.Format<"uuid">,
  ): Output => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: path(id),
      contentType: "application/json",
    });
    assert.param("id")(() => typia.assert(id));
    return random();
  };
}


