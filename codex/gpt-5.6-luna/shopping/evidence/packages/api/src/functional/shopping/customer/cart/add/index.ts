import type * as api from "@benchmark/shopping2-api";
import { type IConnection, NestiaSimulator, PlainFetcher } from "@nestia/fetcher";
import typia, { type Primitive, Resolved } from "typia";

/**
 * Add a variant to the cart.
 *
 * @evidence docs/analysis/03-functional-requirements.md#req-cart-functions-1-add-a-variant-to-the-cart This operation implements the referenced requirement at the generated API boundary.
 * @evidence prisma:shopping_cart_lines This operation uses the referenced persistence model for its request or response data.
 *
 * @controller ShoppingCommerceController.cartAdd
 * @path POST /shopping/customer/cart/add
 * @accessor api.functional.shopping.customer.cart.add.cartAdd
 * @nestia Generated by Nestia - https://github.com/samchon/nestia
 */
export async function cartAdd(
  connection: IConnection<cartAdd.Headers>,
  body: cartAdd.Body,
): Promise<cartAdd.Output> {
  return true === connection.simulate
    ? cartAdd.simulate(connection, body)
    : PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...cartAdd.METADATA,
          template: cartAdd.METADATA.path,
          path: cartAdd.path(),
        },
        body,
      );
}
export namespace cartAdd {
  export type Headers = Resolved<{ authorization?: string }>;
  export type Body = Primitive<api.IShoppingCart.ICreate>;
  export type Output = Primitive<api.IShoppingCart>;

  export const METADATA = {
    method: "POST",
    path: "/shopping/customer/cart/add",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
    status: 201,
  } as const;

  export const path = () => "/shopping/customer/cart/add";
  export const random = (): Resolved<Primitive<api.IShoppingCart>> =>
    typia.random<Primitive<api.IShoppingCart>>();
  export const simulate = (
    connection: IConnection<cartAdd.Headers>,
    body: Body,
  ): Output => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: path(),
      contentType: "application/json",
    });
    assert.body(() => typia.assert(body));
    return random();
  };
}


