import type * as api from "@benchmark/shopping2-api";
import { type IConnection, NestiaSimulator, PlainFetcher } from "@nestia/fetcher";
import typia, { type Primitive, Resolved, tags } from "typia";

/**
 * Unban a customer.
 *
 * @evidence docs/analysis/03-functional-requirements.md#req-user-oversight-3-unban-a-customer This operation implements the referenced requirement at the generated API boundary.
 *
 * @controller ShoppingAdminGovernanceController.unbanCustomer
 * @path PUT /shopping/admin/user/customer/:id/unban
 * @accessor api.functional.shopping.admin.user.customer.unban.unbanCustomer
 * @nestia Generated by Nestia - https://github.com/samchon/nestia
 */
export async function unbanCustomer(
  connection: IConnection<unbanCustomer.Headers>,
  id: string & tags.Format<"uuid">,
): Promise<unbanCustomer.Output> {
  return true === connection.simulate
    ? unbanCustomer.simulate(connection, id)
    : PlainFetcher.fetch(connection, {
        ...unbanCustomer.METADATA,
        template: unbanCustomer.METADATA.path,
        path: unbanCustomer.path(id),
      });
}
export namespace unbanCustomer {
  export type Headers = Resolved<{ authorization?: string }>;
  export type Output = Primitive<api.IShoppingResult>;

  export const METADATA = {
    method: "PUT",
    path: "/shopping/admin/user/customer/:id/unban",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
    status: 200,
  } as const;

  export const path = (id: string & tags.Format<"uuid">) =>
    `/shopping/admin/user/customer/${encodeURIComponent(
      id?.toString() ?? "null",
    )}/unban`;
  export const random = (): Resolved<Primitive<api.IShoppingResult>> =>
    typia.random<Primitive<api.IShoppingResult>>();
  export const simulate = (
    connection: IConnection<unbanCustomer.Headers>,
    id: string & tags.Format<"uuid">,
  ): Output => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: path(id),
      contentType: "application/json",
    });
    assert.param("id")(() => typia.assert(id));
    return random();
  };
}


