/**
 * Recover from payment failure without committing effects.
 *
 * @evidence docs/analysis/03-functional-requirements.md#req-checkout-journey-4-recover-from-payment-failure This operation implements the referenced requirement at the generated API boundary.
 * @evidence docs/analysis/05-non-functional.md#req-nfr-purchase-consistency-2-preserve-a-clean-state-after-payment-failure Enforces the purchase consistency 2 preserve a clean state after payment failure contract through checkoutFailure.
 *
 * @controller ShoppingCommerceController.checkoutFailure
 * @path POST /shopping/customer/checkout/failure
 * @accessor api.functional.shopping.customer.checkout.failure.checkoutFailure
 * @nestia Generated by Nestia - https://github.com/samchon/nestia
 */
export async function checkoutFailure(
  connection: IConnection,
): Promise<checkoutFailure.Output> {
  return true === connection.simulate
    ? checkoutFailure.simulate(connection)
    : PlainFetcher.fetch(connection, {
        ...checkoutFailure.METADATA,
        template: checkoutFailure.METADATA.path,
        path: checkoutFailure.path(),
      });
}
export namespace checkoutFailure {
  export type Output = Primitive<api.IShoppingResult>;

  export const METADATA = {
    method: "POST",
    path: "/shopping/customer/checkout/failure",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
    status: 201,
  } as const;

  export const path = () => "/shopping/customer/checkout/failure";
  export const random = (): Resolved<Primitive<api.IShoppingResult>> =>
    typia.random<Primitive<api.IShoppingResult>>();
  export const simulate = (_connection: IConnection): Output => {
    return random();
  };
}


