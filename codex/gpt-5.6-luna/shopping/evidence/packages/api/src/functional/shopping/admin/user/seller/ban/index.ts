import type * as api from "@benchmark/shopping2-api";
import { type IConnection, NestiaSimulator, PlainFetcher } from "@nestia/fetcher";
import typia, { type Primitive, Resolved, tags } from "typia";

/**
 * Ban a seller.
 *
 * @evidence docs/analysis/03-functional-requirements.md#req-user-oversight-5-ban-a-seller This operation implements the referenced requirement at the generated API boundary.
 *
 * @controller ShoppingAdminGovernanceController.banSeller
 * @path PUT /shopping/admin/user/seller/:id/ban
 * @accessor api.functional.shopping.admin.user.seller.ban.banSeller
 * @nestia Generated by Nestia - https://github.com/samchon/nestia
 */
export async function banSeller(
  connection: IConnection<banSeller.Headers>,
  id: string & tags.Format<"uuid">,
): Promise<banSeller.Output> {
  return true === connection.simulate
    ? banSeller.simulate(connection, id)
    : PlainFetcher.fetch(connection, {
        ...banSeller.METADATA,
        template: banSeller.METADATA.path,
        path: banSeller.path(id),
      });
}
export namespace banSeller {
  export type Headers = Resolved<{ authorization?: string }>;
  export type Output = Primitive<api.IShoppingResult>;

  export const METADATA = {
    method: "PUT",
    path: "/shopping/admin/user/seller/:id/ban",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
    status: 200,
  } as const;

  export const path = (id: string & tags.Format<"uuid">) =>
    `/shopping/admin/user/seller/${encodeURIComponent(
      id?.toString() ?? "null",
    )}/ban`;
  export const random = (): Resolved<Primitive<api.IShoppingResult>> =>
    typia.random<Primitive<api.IShoppingResult>>();
  export const simulate = (
    connection: IConnection<banSeller.Headers>,
    id: string & tags.Format<"uuid">,
  ): Output => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: path(id),
      contentType: "application/json",
    });
    assert.param("id")(() => typia.assert(id));
    return random();
  };
}


