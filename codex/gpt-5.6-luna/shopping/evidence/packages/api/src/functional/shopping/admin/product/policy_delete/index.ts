export async function policyDeleteProduct(
  connection: IConnection<policyDeleteProduct.Headers>,
  id: string & tags.Format<"uuid">,
): Promise<policyDeleteProduct.Output> {
  return true === connection.simulate
    ? policyDeleteProduct.simulate(connection, id)
    : PlainFetcher.fetch(connection, {
        ...policyDeleteProduct.METADATA,
        template: policyDeleteProduct.METADATA.path,
        path: policyDeleteProduct.path(id),
      });
}
