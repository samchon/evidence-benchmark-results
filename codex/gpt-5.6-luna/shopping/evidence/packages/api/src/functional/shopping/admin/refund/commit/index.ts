import type * as api from "@benchmark/shopping2-api";
import { type IConnection, NestiaSimulator, PlainFetcher } from "@nestia/fetcher";
import typia, { type Primitive, Resolved, tags } from "typia";

/**
 * Commit approved refund effects.
 *
 * @evidence docs/analysis/03-functional-requirements.md#req-refund-functions-5-commit-approved-refund-effects This operation implements the referenced requirement at the generated API boundary.
 * @evidence prisma:shopping_order_items This operation uses the referenced persistence model for its request or response data.
 *
 * @controller ShoppingFulfillmentController.refundCommit
 * @path PUT /shopping/admin/refund/:id/commit
 * @accessor api.functional.shopping.admin.refund.commit.refundCommit
 * @nestia Generated by Nestia - https://github.com/samchon/nestia
 */
export async function refundCommit(
  connection: IConnection<refundCommit.Headers>,
  id: string & tags.Format<"uuid">,
): Promise<refundCommit.Output> {
  return true === connection.simulate
    ? refundCommit.simulate(connection, id)
    : PlainFetcher.fetch(connection, {
        ...refundCommit.METADATA,
        template: refundCommit.METADATA.path,
        path: refundCommit.path(id),
      });
}
export namespace refundCommit {
  export type Headers = Resolved<{ authorization?: string }>;
  export type Output = Primitive<api.IShoppingResult>;

  export const METADATA = {
    method: "PUT",
    path: "/shopping/admin/refund/:id/commit",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
    status: 200,
  } as const;

  export const path = (id: string & tags.Format<"uuid">) =>
    `/shopping/admin/refund/${encodeURIComponent(
      id?.toString() ?? "null",
    )}/commit`;
  export const random = (): Resolved<Primitive<api.IShoppingResult>> =>
    typia.random<Primitive<api.IShoppingResult>>();
  export const simulate = (
    connection: IConnection<refundCommit.Headers>,
    id: string & tags.Format<"uuid">,
  ): Output => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: path(id),
      contentType: "application/json",
    });
    assert.param("id")(() => typia.assert(id));
    return random();
  };
}


