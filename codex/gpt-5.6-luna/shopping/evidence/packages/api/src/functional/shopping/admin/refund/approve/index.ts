import type * as api from "@benchmark/shopping2-api";
import { type IConnection, NestiaSimulator, PlainFetcher } from "@nestia/fetcher";
import typia, { type Primitive, Resolved, tags } from "typia";

/**
 * Approve item refund.
 *
 * @evidence docs/analysis/03-functional-requirements.md#req-refund-functions-3-approve-an-item-refund This operation implements the referenced requirement at the generated API boundary.
 * @evidence prisma:shopping_refund_requests This operation uses the referenced persistence model for its request or response data.
 *
 * @controller ShoppingFulfillmentController.refundApprove
 * @path PUT /shopping/admin/refund/:id/approve
 * @accessor api.functional.shopping.admin.refund.approve.refundApprove
 * @nestia Generated by Nestia - https://github.com/samchon/nestia
 */
export async function refundApprove(
  connection: IConnection<refundApprove.Headers>,
  id: string & tags.Format<"uuid">,
): Promise<refundApprove.Output> {
  return true === connection.simulate
    ? refundApprove.simulate(connection, id)
    : PlainFetcher.fetch(connection, {
        ...refundApprove.METADATA,
        template: refundApprove.METADATA.path,
        path: refundApprove.path(id),
      });
}
export namespace refundApprove {
  export type Headers = Resolved<{ authorization?: string }>;
  export type Output = Primitive<api.IShoppingResult>;

  export const METADATA = {
    method: "PUT",
    path: "/shopping/admin/refund/:id/approve",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
    status: 200,
  } as const;

  export const path = (id: string & tags.Format<"uuid">) =>
    `/shopping/admin/refund/${encodeURIComponent(
      id?.toString() ?? "null",
    )}/approve`;
  export const random = (): Resolved<Primitive<api.IShoppingResult>> =>
    typia.random<Primitive<api.IShoppingResult>>();
  export const simulate = (
    connection: IConnection<refundApprove.Headers>,
    id: string & tags.Format<"uuid">,
  ): Output => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: path(id),
      contentType: "application/json",
    });
    assert.param("id")(() => typia.assert(id));
    return random();
  };
}


