import type * as api from "@benchmark/shopping2-api";
import { type IConnection, NestiaSimulator, PlainFetcher } from "@nestia/fetcher";
import typia, { type Primitive, Resolved, tags } from "typia";

/**
 * Approve item cancellation.
 *
 * @evidence docs/analysis/03-functional-requirements.md#req-cancellation-functions-3-approve-item-cancellation This operation implements the referenced requirement at the generated API boundary.
 * @evidence prisma:shopping_cancellation_requests This operation uses the referenced persistence model for its request or response data.
 *
 * @controller ShoppingFulfillmentController.cancellationApprove
 * @path PUT /shopping/admin/cancellation/:id/approve
 * @accessor api.functional.shopping.admin.cancellation.approve.cancellationApprove
 * @nestia Generated by Nestia - https://github.com/samchon/nestia
 */
export async function cancellationApprove(
  connection: IConnection<cancellationApprove.Headers>,
  id: string & tags.Format<"uuid">,
): Promise<cancellationApprove.Output> {
  return true === connection.simulate
    ? cancellationApprove.simulate(connection, id)
    : PlainFetcher.fetch(connection, {
        ...cancellationApprove.METADATA,
        template: cancellationApprove.METADATA.path,
        path: cancellationApprove.path(id),
      });
}
export namespace cancellationApprove {
  export type Headers = Resolved<{ authorization?: string }>;
  export type Output = Primitive<api.IShoppingResult>;

  export const METADATA = {
    method: "PUT",
    path: "/shopping/admin/cancellation/:id/approve",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
    status: 200,
  } as const;

  export const path = (id: string & tags.Format<"uuid">) =>
    `/shopping/admin/cancellation/${encodeURIComponent(
      id?.toString() ?? "null",
    )}/approve`;
  export const random = (): Resolved<Primitive<api.IShoppingResult>> =>
    typia.random<Primitive<api.IShoppingResult>>();
  export const simulate = (
    connection: IConnection<cancellationApprove.Headers>,
    id: string & tags.Format<"uuid">,
  ): Output => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: path(id),
      contentType: "application/json",
    });
    assert.param("id")(() => typia.assert(id));
    return random();
  };
}


