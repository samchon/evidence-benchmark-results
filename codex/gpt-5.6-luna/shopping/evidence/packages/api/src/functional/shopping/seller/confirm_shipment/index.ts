import type * as api from "@benchmark/shopping2-api";
import { type IConnection, NestiaSimulator, PlainFetcher } from "@nestia/fetcher";
import typia, { type Primitive, Resolved, tags } from "typia";

/**
 * Confirm shipment delivery.
 *
 * @evidence docs/analysis/03-functional-requirements.md#req-shipping-functions-4-confirm-shipment-delivery This operation implements the referenced requirement at the generated API boundary.
 * @evidence prisma:shopping_shipments This operation uses the referenced persistence model for its request or response data.
 *
 * @controller ShoppingFulfillmentController.confirm
 * @path PUT /shopping/seller/confirm-shipment/:id
 * @accessor api.functional.shopping.seller.confirm_shipment.confirm
 * @nestia Generated by Nestia - https://github.com/samchon/nestia
 */
export async function confirm(
  connection: IConnection<confirm.Headers>,
  id: string & tags.Format<"uuid">,
): Promise<confirm.Output> {
  return true === connection.simulate
    ? confirm.simulate(connection, id)
    : PlainFetcher.fetch(connection, {
        ...confirm.METADATA,
        template: confirm.METADATA.path,
        path: confirm.path(id),
      });
}
export namespace confirm {
  export type Headers = Resolved<{ authorization?: string }>;
  export type Output = Primitive<api.IShoppingOrder.IShipment>;

  export const METADATA = {
    method: "PUT",
    path: "/shopping/seller/confirm-shipment/:id",
    request: null,
    response: {
      type: "application/json",
      encrypted: false,
    },
    status: 200,
  } as const;

  export const path = (id: string & tags.Format<"uuid">) =>
    `/shopping/seller/confirm-shipment/${encodeURIComponent(
      id?.toString() ?? "null",
    )}`;
  export const random = (): Resolved<Primitive<api.IShoppingOrder.IShipment>> =>
    typia.random<Primitive<api.IShoppingOrder.IShipment>>();
  export const simulate = (
    connection: IConnection<confirm.Headers>,
    id: string & tags.Format<"uuid">,
  ): Output => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: path(id),
      contentType: "application/json",
    });
    assert.param("id")(() => typia.assert(id));
    return random();
  };
}


