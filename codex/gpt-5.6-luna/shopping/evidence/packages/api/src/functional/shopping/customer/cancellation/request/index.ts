import type * as api from "@benchmark/shopping2-api";
import { type IConnection, NestiaSimulator, PlainFetcher } from "@nestia/fetcher";
import typia, { type Primitive, Resolved, tags } from "typia";

/**
 * Request item cancellation.
 *
 * @evidence docs/analysis/03-functional-requirements.md#req-cancellation-functions-1-request-item-cancellation This operation implements the referenced requirement at the generated API boundary.
 * @evidence prisma:shopping_cancellation_requests This operation uses the referenced persistence model for its request or response data.
 *
 * @controller ShoppingFulfillmentController.cancellationRequest
 * @path POST /shopping/customer/cancellation/:itemId/request
 * @accessor api.functional.shopping.customer.cancellation.request.cancellationRequest
 * @nestia Generated by Nestia - https://github.com/samchon/nestia
 */
export async function cancellationRequest(
  connection: IConnection<cancellationRequest.Headers>,
  itemId: string & tags.Format<"uuid">,
  body: cancellationRequest.Body,
): Promise<cancellationRequest.Output> {
  return true === connection.simulate
    ? cancellationRequest.simulate(connection, itemId, body)
    : PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...cancellationRequest.METADATA,
          template: cancellationRequest.METADATA.path,
          path: cancellationRequest.path(itemId),
        },
        body,
      );
}
export namespace cancellationRequest {
  export type Headers = Resolved<{ authorization?: string }>;
  export type Body = Primitive<api.IShoppingOrder.IItemAction>;
  export type Output = Primitive<api.IShoppingResult>;

  export const METADATA = {
    method: "POST",
    path: "/shopping/customer/cancellation/:itemId/request",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
    status: 201,
  } as const;

  export const path = (itemId: string & tags.Format<"uuid">) =>
    `/shopping/customer/cancellation/${encodeURIComponent(
      itemId?.toString() ?? "null",
    )}/request`;
  export const random = (): Resolved<Primitive<api.IShoppingResult>> =>
    typia.random<Primitive<api.IShoppingResult>>();
  export const simulate = (
    connection: IConnection<cancellationRequest.Headers>,
    itemId: string & tags.Format<"uuid">,
    body: Body,
  ): Output => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: path(itemId),
      contentType: "application/json",
    });
    assert.param("itemId")(() => typia.assert(itemId));
    assert.body(() => typia.assert(body));
    return random();
  };
}


