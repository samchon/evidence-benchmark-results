import type * as api from "@benchmark/shopping2-api";
import { type IConnection, NestiaSimulator, PlainFetcher } from "@nestia/fetcher";
import typia, { type Primitive, Resolved, tags } from "typia";

/**
 * Change cart quantity.
 *
 * @evidence docs/analysis/03-functional-requirements.md#req-cart-functions-3-change-cart-quantity This operation implements the referenced requirement at the generated API boundary.
 * @evidence prisma:shopping_cart_lines This operation uses the referenced persistence model for its request or response data.
 *
 * @controller ShoppingCommerceController.cartUpdate
 * @path PUT /shopping/customer/cart/:id/update
 * @accessor api.functional.shopping.customer.cart.update.cartUpdate
 * @nestia Generated by Nestia - https://github.com/samchon/nestia
 */
export async function cartUpdate(
  connection: IConnection<cartUpdate.Headers>,
  id: string & tags.Format<"uuid">,
  body: cartUpdate.Body,
): Promise<cartUpdate.Output> {
  return true === connection.simulate
    ? cartUpdate.simulate(connection, id, body)
    : PlainFetcher.fetch(
        {
          ...connection,
          headers: {
            ...connection.headers,
            "Content-Type": "application/json",
          },
        },
        {
          ...cartUpdate.METADATA,
          template: cartUpdate.METADATA.path,
          path: cartUpdate.path(id),
        },
        body,
      );
}
export namespace cartUpdate {
  export type Headers = Resolved<{ authorization?: string }>;
  export type Body = Primitive<api.IShoppingCart.IUpdate>;
  export type Output = Primitive<api.IShoppingCart>;

  export const METADATA = {
    method: "PUT",
    path: "/shopping/customer/cart/:id/update",
    request: {
      type: "application/json",
      encrypted: false,
    },
    response: {
      type: "application/json",
      encrypted: false,
    },
    status: 200,
  } as const;

  export const path = (id: string & tags.Format<"uuid">) =>
    `/shopping/customer/cart/${encodeURIComponent(
      id?.toString() ?? "null",
    )}/update`;
  export const random = (): Resolved<Primitive<api.IShoppingCart>> =>
    typia.random<Primitive<api.IShoppingCart>>();
  export const simulate = (
    connection: IConnection<cartUpdate.Headers>,
    id: string & tags.Format<"uuid">,
    body: Body,
  ): Output => {
    const assert = NestiaSimulator.assert({
      method: METADATA.method,
      host: connection.host,
      path: path(id),
      contentType: "application/json",
    });
    assert.param("id")(() => typia.assert(id));
    assert.body(() => typia.assert(body));
    return random();
  };
}


